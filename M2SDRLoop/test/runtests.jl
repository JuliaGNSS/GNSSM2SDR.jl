    @testset "the board's record stream, read through a pipe" begin
        csr = LiteXCSR(write_csr_csv(joinpath(mktempdir(), "csr.csv")); device = nothing)
        io = LitePCIeTDM(csr; dma_device = "pipe")
        rfd, wfd = nonblocking_pipe()
        stream = DMAWriterStream(rfd, "pipe", UInt8[], zeros(UInt8, 24), true)
        io.stream = stream
        @test M2SDRLoop.dma_open!(io) === io && io.stream === stream
        buf = zeros(UInt8, 1024)
        # Nothing yet: the read would block.
        @test M2SDRLoop.dma_wait(io, 0) == false
        @test M2SDRLoop.dma_read!(io, buf, 0) == 0
        block = rand(MersenneTwister(5), UInt8, 512)
        ccall(:write, Cssize_t, (Cint, Ptr{UInt8}, Csize_t), wfd, block, 512)
        @test M2SDRLoop.dma_wait(io, 1000)
        # No room for a whole buffer after the first 600 bytes.
        @test M2SDRLoop.dma_read!(io, buf, 600) == 0
        @test M2SDRLoop.dma_read!(io, buf, 100) == 512
        @test buf[101:612] == block
        ccall(:close, Cint, (Cint,), wfd)
        @test M2SDRLoop.dma_read!(io, buf, 0) == 0     # end of file
        @test_throws SystemError M2SDRLoop._read_into!(Cint(-1), buf, 0)
        # Closing stops the writer and drops the lock best effort, and closes the fd.
        M2SDRLoop.dma_close!(io)
        @test isnothing(io.stream) && !stream.open
        @test close(stream) === stream
    end

