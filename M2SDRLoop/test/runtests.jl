const FS = 4e6
const L1 = 1575.42e6

# A satellite on one antenna: `signal` (GPS L1 C/A unless given) `prn` at
# `doppler` (Hz) and `code_phase` (chips at sample 0), at `cn0` dBHz in
# unit-variance-per-component noise scaled by `sigma`, quantised to the
# AD9361's 12 bits. A CBOC code is GNSSSignals' float one, of unit power.
function synthetic(
    n,
    first_sample;
    prn,
    doppler,
    code_phase,
    cn0,
    sigma = 60.0,
    rng,
    signal = GPSL1CA(),
)
    s = signal
    code_rate = 1.023e6 * (1 + doppler / L1)
    amp = sqrt(10^(cn0 / 10) * 2 * sigma^2 / FS)
    out = Vector{Complex{Int16}}(undef, n)
    for k = 1:n
        t = (first_sample + k - 1) / FS
        chip = get_code(s, code_phase + code_rate * t, prn)
        z = amp * chip * cis(2π * doppler * t) + sigma * complex(randn(rng), randn(rng))
        out[k] = Complex{Int16}(
            clamp(round(Int, real(z)), -2048, 2047),
            clamp(round(Int, imag(z)), -2048, 2047),
        )
    end
    out
end

new_driver(emu; kwargs...) =
    TDMDriver(emu, emulator_regs(), (GPSL1CA(),); fs = FS, kwargs...)

# A `csr.csv` with the emulator's register layout, as LiteX writes it.
function write_csr_csv(
    path;
    names = M2SDRLoop.TDM_REG_NAMES,
    optional = true,
    extra = String[],
    data_width = 32,
)
    regs = emulator_regs()
    open(path, "w") do io
        println(
            io,
            "#--------------------------------------------------------------------------------",
        )
        println(io, "# Auto-generated by LiteX")
        println(io, "csr_base,gnss,0x00000000,,")
        println(io, "constant,config_csr_data_width,$data_width,,")
        println(io)
        for (k, name) in enumerate(M2SDRLoop.TDM_REG_NAMES)
            name in names || continue
            println(
                io,
                "csr_register,gnss_$name,0x$(string(getfield(regs, k); base = 16)),1,rw",
            )
        end
        if optional
            println(
                io,
                "csr_register,pcie_dma1_synchronizer_bypass,$(regs.dma1_sync_bypass),1,rw",
            )
            println(io, "csr_register,ad9361_phy_control,$(regs.phy_control),1,rw")
            # Interface revision 2's replica registers.
            println(io, "csr_register,gnss_s_subcarrier,$(regs.s_subcarrier),1,rw")
            println(io, "csr_register,gnss_s_amplitude,$(regs.s_amplitude),1,rw")
        end
        foreach(line -> println(io, line), extra)
    end
    path
end

# `f()` with everything it prints, `gnss_loop`'s reports included, going to `path`.
with_stdout_to(f, path) = open(io -> redirect_stdout(f, io), path, "w")

# Both ends of a pipe, the read end non-blocking as the DMA device is opened.
function nonblocking_pipe()
    fds = Vector{Cint}(undef, 2)
    @test ccall(:pipe, Cint, (Ptr{Cint},), fds) == 0
    flags = ccall(:fcntl, Cint, (Cint, Cint, Cint), fds[1], 3 #= F_GETFL =#, 0)
    ccall(:fcntl, Cint, (Cint, Cint, Cint), fds[1], 4 #= F_SETFL =#, flags | 0o4000)
    fds[1], fds[2]
end

